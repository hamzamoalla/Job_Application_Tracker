"""
Gmail → API import logic, adapted from the original mail_reader.py to run
inside a container without a browser.

Key difference vs. the original script: this NEVER runs the interactive
OAuth consent flow (InstalledAppFlow.run_local_server), because there is no
browser inside the container to complete it. token.json must already exist
and be valid (or refreshable) — generate it once on your own machine (run
the original mail_reader.py locally, or any script that does the OAuth
dance) and upload it through this service's /auth/upload endpoint.

Only token.json is needed here: when google-auth's InstalledAppFlow saves a
token via creds.to_json(), it writes the client_id, client_secret, and
refresh_token into that same file — so a valid token.json is self-contained
and can refresh itself without credentials.json ever being present in this
container.
"""

from __future__ import annotations

import base64
import logging
import os
import re
from email.utils import parsedate_to_datetime
from html.parser import HTMLParser
from pathlib import Path

import requests
from google.auth.transport.requests import Request
from google.oauth2.credentials import Credentials
from googleapiclient.discovery import build

logger = logging.getLogger(__name__)

SCOPES = ["https://www.googleapis.com/auth/gmail.readonly"]

AUTH_DIR = Path(os.getenv("AUTH_DIR", "/app/auth"))
TOKEN_FILE = AUTH_DIR / "token.json"

API_URL = os.getenv("API_URL", "http://api:8000/emails")
REQUEST_TIMEOUT = 20

# Gmail system labels used to fetch each direction separately, instead of
# fetching everything and guessing direction per message like the original
# script did.
LABEL_BY_DIRECTION = {
    "SENT": "SENT",
    "RECEIVED": "INBOX",
}


class GmailAuthError(RuntimeError):
    """Raised when there is no usable token.json in AUTH_DIR."""


# ============================================================
# AUTH STATUS / FILE HANDLING
# ============================================================


def auth_status() -> dict:
    return {
        "token_json": TOKEN_FILE.exists(),
    }


def save_uploaded_token(token_bytes: bytes) -> dict:
    AUTH_DIR.mkdir(parents=True, exist_ok=True)
    TOKEN_FILE.write_bytes(token_bytes)
    logger.info("token.json saved to %s", TOKEN_FILE)
    return auth_status()


# ============================================================
# GMAIL AUTHENTICATION (no browser — token.json must already exist)
# ============================================================


def authenticate_gmail():
    if not TOKEN_FILE.exists():
        raise GmailAuthError(
            "token.json not found. This container has no browser to run the "
            "Google OAuth consent screen, so you need to generate token.json "
            "once on your own machine and upload it via /auth/upload."
        )

    try:
        creds = Credentials.from_authorized_user_file(str(TOKEN_FILE), SCOPES)
    except ValueError as exc:
        raise GmailAuthError(
            f"token.json is not a valid Google OAuth token file ({exc}). "
            "Re-upload the token.json generated by the OAuth consent flow "
            "on your own machine."
        ) from exc

    if creds.expired and creds.refresh_token:
        creds.refresh(Request())
        TOKEN_FILE.write_text(creds.to_json(), encoding="utf-8")
        logger.info("token.json refreshed")

    if not creds.valid:
        raise GmailAuthError(
            "token.json is present but not valid and could not be refreshed "
            "(no refresh token, or it was revoked). Regenerate it locally "
            "and upload it again."
        )

    return build("gmail", "v1", credentials=creds)


def get_my_email(service) -> str:
    profile = service.users().getProfile(userId="me").execute()
    return profile["emailAddress"]


