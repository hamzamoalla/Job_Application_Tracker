# HEADER / BODY HELPERS (unchanged from mail_reader.py)
# ============================================================


def get_header(headers, name):
    for header in headers:
        if header.get("name", "").lower() == name.lower():
            return header.get("value", "")
    return ""


def decode_body(data):
    if not data:
        return ""
    try:
        decoded = base64.urlsafe_b64decode(data)
        return decoded.decode("utf-8", errors="replace")
    except (ValueError, TypeError):
        return ""


class HTMLTextExtractor(HTMLParser):
    BLOCK_TAGS = {"p", "div", "br", "tr", "li", "h1", "h2", "h3", "h4", "blockquote"}

    def __init__(self):
        super().__init__(convert_charrefs=True)
        self.text_parts = []
        self.hidden_tags = []

    def handle_starttag(self, tag, attrs):
        if tag in ("script", "style"):
            self.hidden_tags.append(tag)
            return
        if not self.hidden_tags and tag in self.BLOCK_TAGS:
            self.text_parts.append("\n")

    def handle_endtag(self, tag):
        if tag in ("script", "style"):
            for index in range(len(self.hidden_tags) - 1, -1, -1):
                if self.hidden_tags[index] == tag:
                    del self.hidden_tags[index]
                    break
            return
        if not self.hidden_tags and tag in self.BLOCK_TAGS:
            self.text_parts.append("\n")

    def handle_data(self, data):
        if not self.hidden_tags:
            self.text_parts.append(data)


def html_to_text(html):
    parser = HTMLTextExtractor()
    parser.feed(html)
    parser.close()
    lines = [line.strip() for line in "".join(parser.text_parts).splitlines() if line.strip()]
    return "\n".join(lines)


def clean_body_text(text: str) -> str:
    if not text:
        return ""

    text = re.sub(
        r"[\u0000-\u0008\u000B\u000C\u000E-\u001F"
        r"​-‏‪-‮⁠-⁤⁦-⁯"
        r"﻿­͏؜᠎ - ]",
        "",
        text,
    )

    text = re.sub(r"\bNone\s*\[\d+\]", "", text)
    text = re.sub(r"\[\d+\]", "", text)
    text = re.sub(r"[ \t]+", " ", text)
    text = re.sub(r"\n{3,}", "\n\n", text).strip()

    lines = text.splitlines()
    while lines:
        last_line = lines[-1].strip()
        if not last_line:
            lines.pop()
            continue
        if re.match(r"^(mailto:|https?://|http://|www\.)\S+$", last_line, re.IGNORECASE):
            lines.pop()
        else:
            break
    text = "\n".join(lines).strip()

    parts = re.split(r"\n{2,}", text)
    if len(parts) >= 2:
        p0 = parts[0].strip()
        rest = "\n\n".join(parts[1:]).strip()

        has_ellipsis = bool(re.search(r"(\[\s*\.\.\.\s*\]|\.\.\.|\…)\s*$", p0))
        p0_clean = re.sub(r"(\[\s*\.\.\.\s*\]|\.\.\.|\…|\*)\s*$", "", p0).strip()

        def norm(s):
            return re.sub(r"\s+", " ", s).strip().lower()

        p0_norm = norm(p0_clean)
        rest_norm = norm(rest)

        if p0_norm and len(p0_norm) < 400:
            if has_ellipsis and rest_norm.startswith(p0_norm[:40]):
                text = rest
            elif rest_norm.startswith(p0_norm):
                text = rest

    return text.strip()


def collect_mime_bodies(part, plain_parts, html_parts):
    if part.get("filename"):
        return

    mime_type = part.get("mimeType", "").lower()
    body_data = part.get("body", {}).get("data")

    if body_data:
        decoded = decode_body(body_data)
        if mime_type == "text/plain":
            plain_parts.append(decoded)
        elif mime_type == "text/html":
            html_parts.append(decoded)

    for child in part.get("parts", []):
        collect_mime_bodies(child, plain_parts, html_parts)


def extract_body(payload):
    plain_parts: list[str] = []
    html_parts: list[str] = []

    collect_mime_bodies(payload, plain_parts, html_parts)

    plain_text = "\n".join(part.strip() for part in plain_parts if part.strip())
    if plain_text:
        return clean_body_text(plain_text)

    html_text = "\n".join(part for part in html_parts if part.strip())
    if html_text:
        return clean_body_text(html_to_text(html_text))

    return ""


def parse_date(date_string):
    if not date_string:
        return None
    try:
        return parsedate_to_datetime(date_string).isoformat()
    except (TypeError, ValueError, OverflowError):
        return None


def convert_message(service, message, direction: str):
    message_id = message["id"]

    full_message = (
        service.users().messages().get(userId="me", id=message_id, format="full").execute()
    )

    payload = full_message.get("payload", {})
    headers = payload.get("headers", [])

    return {
        "gmail_id": full_message["id"],
        "thread_id": full_message["threadId"],
        "direction": direction,
        "sender": get_header(headers, "From"),
        "recipient": get_header(headers, "To"),
        "subject": get_header(headers, "Subject"),
        "body": extract_body(payload),
        "sent_at": parse_date(get_header(headers, "Date")),
    }


# ============================================================
# LIST MESSAGES FOR ONE DIRECTION (SENT or RECEIVED)
# ============================================================


def list_messages(service, label_id: str, max_results: int):
    messages = []
    page_token = None

    while len(messages) < max_results:
        remaining = max_results - len(messages)
        params = {
            "userId": "me",
            "labelIds": [label_id],
            "maxResults": min(remaining, 500),
        }
        if page_token:
            params["pageToken"] = page_token

        response = service.users().messages().list(**params).execute()
        messages.extend(response.get("messages", []))
        page_token = response.get("nextPageToken")
        if not page_token:
            break

    return messages[:max_results]


def send_email_to_api(email: dict) -> dict | None:
    try:
        response = requests.post(API_URL, json=email, timeout=REQUEST_TIMEOUT)
        response.raise_for_status()
        if response.content:
            try:
                return response.json()
            except ValueError:
                return {"success": True, "response": response.text}
        return {"success": True}
    except requests.exceptions.RequestException as error:
        logger.warning("Failed to send email %s to API: %s", email.get("gmail_id"), error)
        return None


# ============================================================
# MAIN ENTRY POINT USED BY THE API
# ============================================================


def run_import(max_sent: int, max_received: int) -> dict:
    """
    Fetch up to max_sent SENT emails and max_received RECEIVED emails and
    push each one to the main API. Returns a summary dict; never raises for
    individual message failures (only for an auth problem upfront).
    """

    service = authenticate_gmail()
    my_email = get_my_email(service)

    summary = {
        "account": my_email,
        "sent": {"found": 0, "imported": 0, "failed": 0},
        "received": {"found": 0, "imported": 0, "failed": 0},
    }

    for direction, limit in (("SENT", max_sent), ("RECEIVED", max_received)):
        if limit <= 0:
            continue

        label_id = LABEL_BY_DIRECTION[direction]
        key = direction.lower()
        messages = list_messages(service, label_id, limit)
        summary[key]["found"] = len(messages)

        for message in messages:
            try:
                email = convert_message(service, message, direction)
            except Exception:
                logger.exception("Failed to convert message %s", message.get("id"))
                summary[key]["failed"] += 1
                continue

            result = send_email_to_api(email)
            if result is not None:
                summary[key]["imported"] += 1
            else:
                summary[key]["failed"] += 1

    return summary
