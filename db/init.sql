-- ============================================================
-- Job Application Tracker — schéma complet de la base de données
-- Reconstruit à partir de l'état réel de la base (\dt / \d),
-- dans l'ordre qui respecte les contraintes de clé étrangère.
-- ============================================================

-- ------------------------------------------------------------
-- app_users
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS app_users (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email         text NOT NULL,
    password_hash text NOT NULL,
    first_name    text NOT NULL DEFAULT '',
    last_name     text NOT NULL DEFAULT '',
    company       text NOT NULL DEFAULT '',
    created_at    timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT app_users_email_key UNIQUE (email)
);

-- ------------------------------------------------------------
-- app_sessions
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS app_sessions (
    token      text PRIMARY KEY,
    user_id    bigint NOT NULL REFERENCES app_users(id) ON DELETE CASCADE,
    created_at timestamptz NOT NULL DEFAULT now(),
    expires_at timestamptz NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_app_sessions_expires ON app_sessions (expires_at);
CREATE INDEX IF NOT EXISTS idx_app_sessions_user    ON app_sessions (user_id);

-- ------------------------------------------------------------
-- emails
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS emails (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    gmail_id         text NOT NULL,
    thread_id        text NOT NULL,
    direction        text NOT NULL,
    sender           text,
    recipient        text,
    subject          text,
    body             text,
    sent_at          timestamptz,
    processed        boolean NOT NULL DEFAULT false,
    classification   text,
    confidence       double precision,
    classified_by    text,
    created_at       timestamptz NOT NULL DEFAULT now(),
    review_dismissed boolean NOT NULL DEFAULT false,
    CONSTRAINT emails_gmail_id_key UNIQUE (gmail_id),
    CONSTRAINT emails_direction_check CHECK (direction = ANY (ARRAY['SENT', 'RECEIVED']))
);

CREATE INDEX IF NOT EXISTS idx_emails_processed ON emails (processed);
CREATE INDEX IF NOT EXISTS idx_emails_sent_at   ON emails (sent_at DESC);
CREATE INDEX IF NOT EXISTS idx_emails_thread_id ON emails (thread_id);

-- ------------------------------------------------------------
-- applications
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS applications (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    thread_id         text NOT NULL,
    company           text,
    position          text,
    application_date  timestamptz,
    status            text NOT NULL DEFAULT 'SENT',
    confidence        double precision,
    sent_email_id     bigint REFERENCES emails(id),
    last_email_id     bigint REFERENCES emails(id),
    source            text NOT NULL DEFAULT 'UNKNOWN',
    created_at        timestamptz NOT NULL DEFAULT now(),
    updated_at        timestamptz NOT NULL DEFAULT now(),
    related_addresses text[] DEFAULT '{}'::text[],
    CONSTRAINT applications_thread_id_key UNIQUE (thread_id)
);

CREATE INDEX IF NOT EXISTS idx_applications_company_position ON applications (company, position);
CREATE INDEX IF NOT EXISTS idx_applications_company_status   ON applications (company, status);
CREATE INDEX IF NOT EXISTS idx_applications_status           ON applications (status);

-- ------------------------------------------------------------
-- application_emails (table d'association applications <-> emails)
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS application_emails (
    application_id integer NOT NULL REFERENCES applications(id) ON DELETE CASCADE,
    email_id       integer NOT NULL REFERENCES emails(id) ON DELETE CASCADE,
    role           text NOT NULL,
    created_at     timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (application_id, email_id),
    CONSTRAINT application_emails_role_check
        CHECK (role = ANY (ARRAY['SENT', 'CONFIRMATION', 'INTERVIEW', 'REJECTION', 'OTHER']))
);

CREATE INDEX IF NOT EXISTS idx_application_emails_app   ON application_emails (application_id);
CREATE INDEX IF NOT EXISTS idx_application_emails_email ON application_emails (email_id);

-- ------------------------------------------------------------
-- processing_events
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS processing_events (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email_id   bigint REFERENCES emails(id),
    event_type text NOT NULL,
    details    jsonb,
    created_at timestamptz NOT NULL DEFAULT now()
);

-- ------------------------------------------------------------
-- review_history
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS review_history (
    id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email_id           bigint,
    action             varchar(50),
    old_classification varchar(50),
    new_classification varchar(50),
    old_confidence     numeric(5,4),
    new_confidence     numeric(5,4),
    add_to_training    boolean DEFAULT false,
    details            text,
    created_at         timestamptz DEFAULT CURRENT_TIMESTAMP
);

-- ------------------------------------------------------------
-- review_queue
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS review_queue (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email_id        bigint REFERENCES emails(id),
    task            text NOT NULL,
    text            text NOT NULL,
    predicted_label text NOT NULL,
    confidence      double precision,
    reviewed        boolean NOT NULL DEFAULT false,
    correct_label   text,
    created_at      timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT review_queue_task_check CHECK (task = ANY (ARRAY['APPLICATION', 'REPLY']))
);

CREATE INDEX IF NOT EXISTS idx_review_queue_reviewed ON review_queue (reviewed);

-- ------------------------------------------------------------
-- training_examples
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS training_examples (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task       text NOT NULL,
    text       text NOT NULL,
    label      text NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    subject    text,
    CONSTRAINT training_examples_task_check CHECK (task = ANY (ARRAY['APPLICATION', 'REPLY'])),
    CONSTRAINT training_examples_task_label_subject_text_key
        UNIQUE (task, label, subject, text)
);